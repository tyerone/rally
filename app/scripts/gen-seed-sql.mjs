// Generates supabase/seed.sql from the existing src/data/tiers.ts and
// checkpoints.ts arrays, so the ~150-row challenge dataset doesn't have to
// be hand-retyped as SQL. Run with:
//   node --experimental-strip-types scripts/gen-seed-sql.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const { TIERS } = await import("../src/data/tiers.ts");
const { CHECKPOINTS } = await import("../src/data/checkpoints.ts");

function sqlStr(v) {
  if (v == null) return "null";
  return `'${String(v).replace(/'/g, "''")}'`;
}

const lines = [];
lines.push("-- Generated by scripts/gen-seed-sql.mjs from src/data/tiers.ts + checkpoints.ts.");
lines.push("-- Run once, after migration.sql, in the Supabase SQL Editor.");
lines.push("");

lines.push("insert into tiers (id, name, tag, accent, icon, blurb, order_index) values");
lines.push(
  TIERS.map((t, i) =>
    `  (${sqlStr(t.id)}, ${sqlStr(t.name)}, ${sqlStr(t.tag)}, ${sqlStr(t.accent)}, ${sqlStr(t.icon)}, ${sqlStr(t.blurb)}, ${i})`
  ).join(",\n") + ";"
);
lines.push("");

lines.push("insert into challenges (tier_id, title, pts, pts_label, meta, tag, description, order_index) values");
const challengeRows = [];
for (const tier of TIERS) {
  tier.cards.forEach((c, i) => {
    challengeRows.push(
      `  (${sqlStr(tier.id)}, ${sqlStr(c.title)}, ${c.pts}, ${sqlStr(c.ptsLabel)}, ${sqlStr(c.meta)}, ${sqlStr(c.tag)}, ${sqlStr(c.desc)}, ${i})`
    );
  });
}
lines.push(challengeRows.join(",\n") + ";");
lines.push("");

lines.push("insert into checkpoints (name, area, lat, lng, color, n) values");
lines.push(
  CHECKPOINTS.map((c) => `  (${sqlStr(c.name)}, ${sqlStr(c.area)}, ${c.lat}, ${c.lng}, ${sqlStr(c.color)}, ${c.n})`).join(",\n") + ";"
);
lines.push("");

const outPath = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${outPath} (${TIERS.length} tiers, ${challengeRows.length} challenges, ${CHECKPOINTS.length} checkpoints)`);
